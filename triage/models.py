"""Data models and schema definitions for the vulnerability triage pipeline.

Operates on plain dataclasses without direct LLM or network dependencies,
enabling isolated unit testing of downstream tools, grounding, and reporting.
"""
from __future__ import annotations

from dataclasses import asdict, dataclass, field
from typing import Any

SEVERITIES: tuple[str, ...] = ("Critical", "High", "Medium", "Low", "None")


@dataclass
class RawFinding:
    """Represents an unverified finding directly from a security scanner.

    All claims generated by the triage agent must be verifiable against
    fields in this finding or the authoritative CWE catalogue.
    """
    id: str
    scanner: str
    kind: str                      # Vulnerability category (e.g. "SQL Injection")
    url: str = ""
    parameter: str = ""
    method: str = "GET"
    payload: str = ""
    evidence: str = ""             # Observed evidence from the scanner
    raw: dict[str, Any] = field(default_factory=dict)

    def evidence_corpus(self) -> str:
        """Combine all factual finding attributes into a single searchable corpus."""
        parts = [
            self.kind, self.url, self.parameter, self.method,
            self.payload, self.evidence, self.scanner,
        ]
        parts += [f"{k}={v}" for k, v in (self.raw or {}).items()]
        return "\n".join(str(p) for p in parts if p)


@dataclass
class TriagedFinding:
    """Represents a triaged and validated vulnerability finding."""
    source_id: str
    title: str
    cwe_id: str = ""               # Authoritative CWE identifier (e.g. "CWE-89")
    cwe_name: str = ""
    cvss_vector: str = ""
    cvss_score: float = 0.0
    severity: str = "None"
    summary: str = ""
    reproduction: str = ""
    remediation: str = ""
    duplicates: list[str] = field(default_factory=list)
    flags: list[str] = field(default_factory=list)   # Grounding or validation warnings
    retries: int = 0

    @property
    def _retries(self) -> int:
        """Backward compatibility alias for retries."""
        return self.retries

    @_retries.setter
    def _retries(self, value: int) -> None:
        self.retries = value

    @property
    def grounded(self) -> bool:
        """Return True if no grounding or consistency flags were raised."""
        return not self.flags

    def to_dict(self) -> dict[str, Any]:
        """Convert the finding to a plain dictionary."""
        return asdict(self)


# Structured JSON schema enforced on model completions.
# Eliminates free-form drift and requires explicit CVSS metrics rather than
# self-reported scores.
TRIAGE_SCHEMA: dict[str, Any] = {
    "type": "object",
    "required": [
        "title", "cwe_id", "cvss_metrics", "summary",
        "reproduction", "remediation",
    ],
    "additionalProperties": False,
    "properties": {
        "title": {"type": "string", "minLength": 8, "maxLength": 120},
        "cwe_id": {"type": "string", "pattern": r"^CWE-\d{1,4}$"},
        "cvss_metrics": {
            "type": "object",
            "required": ["AV", "AC", "PR", "UI", "S", "C", "I", "A"],
            "additionalProperties": False,
            "properties": {
                "AV": {"enum": ["N", "A", "L", "P"]},
                "AC": {"enum": ["L", "H"]},
                "PR": {"enum": ["N", "L", "H"]},
                "UI": {"enum": ["N", "R"]},
                "S":  {"enum": ["U", "C"]},
                "C":  {"enum": ["H", "L", "N"]},
                "I":  {"enum": ["H", "L", "N"]},
                "A":  {"enum": ["H", "L", "N"]},
            },
        },
        "summary": {"type": "string", "minLength": 20, "maxLength": 700},
        "reproduction": {"type": "string", "minLength": 10, "maxLength": 900},
        "remediation": {"type": "string", "minLength": 20, "maxLength": 900},
    },
}
